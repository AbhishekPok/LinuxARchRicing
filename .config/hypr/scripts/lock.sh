#!/usr/bin/env bash
# Lock the session: amane's lock screen, or hyprlock with the active theme
# palette when the shell isn't running.
#
# hyprlock.conf sources ~/.cache/hyprlock/colors.conf, and lock-info.sh reads
# ~/.cache/hyprlock/palette.sh for its pango markup, so both are rewritten here
# from the current theme right before hyprlock starts. Every lock path (keybind,
# hypridle, amane's session menu) goes through this script.

pidof hyprlock >/dev/null && exit 0

amane=$HOME/.cargo/bin/amane

# refresh the weather card's cache in the background; neither lock waits on it
"$HOME/.config/hypr/scripts/lock-info.sh" weather-refresh >/dev/null 2>&1 &

# amane's own lock (~/.config/amane/src/lock.rs) when the shell is up: native
# drawing, mouse input, live data. hyprlock below is the fallback.
case $("$amane" ipc call lock status 2>/dev/null) in
    locked) exit 0 ;;
    unlocked) "$amane" ipc call lock >/dev/null 2>&1 && exit 0 ;;
esac

cache=$HOME/.cache/hyprlock
mkdir -p "$cache"

theme=$(cat "$HOME/.local/state/theme/current" 2>/dev/null)
file=$HOME/.config/theme-manager/themes/$theme

# key from the theme file, without '#', or the fallback
pick() {
    local v
    v=$(sed -n "s/^$1=#\{0,1\}\([0-9A-Fa-f]\{6\}\).*/\1/p" "$file" 2>/dev/null | head -n1)
    echo "${v:-$2}"
}

bg=$(pick BASE00 0a0a0a)
surface=$(pick BASE01 141414)
card=$(pick BASE02 1e1e1e)
outline=$(pick BASE03 3a3a3a)
fg=$(pick BASE05 d4d4d4)
dim=$(pick LIGHT_GREY 8a8a8a)
primary=$(pick BLUE 00b8cc)
secondary=$(pick GREEN 00ff99)
tertiary=$(pick PURPLE bc51ff)
error=$(pick RED ff3e3e)
warn=$(pick ORANGE ff8c00)

cat > "$cache/colors.conf" <<EOF
# generated by lock.sh from theme '$theme' — edit the theme, not this file
\$bg        = rgb($bg)
\$panel     = rgba(${surface}b3)
\$card      = rgba(${card}d9)
\$outline   = rgba(${outline}99)
\$fg        = rgb($fg)
\$dim       = rgb($dim)
\$primary   = rgb($primary)
\$secondary = rgb($secondary)
\$error     = rgb($error)
\$warn      = rgb($warn)
EOF

cat > "$cache/palette.sh" <<EOF
FG=$fg
DIM=$dim
PRIMARY=$primary
SECONDARY=$secondary
TERTIARY=$tertiary
ERROR=$error
WARN=$warn
CARD=$card
EOF

exec hyprlock "$@"
